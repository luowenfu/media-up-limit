export function siteName(host) {
    const name = String(host || '').trim().toLowerCase().replace(/\.$/, '');
    if (!name) return '';
    for (let i = 0; i < SITES.length; i++) {
        const suffix = SITES[i][0];
        if (name === suffix || name.endsWith('.' + suffix)) return SITES[i][1];
    }
    return '';
}
